// Example sketches as polylines in normalized [0, 1] canvas coordinates.

function ellipse(cx, cy, rx, ry, n = 40) {
  const pts = [];
  for (let i = 0; i <= n; i++) {
    const a = (i / n) * 2 * Math.PI;
    pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return pts;
}

function heart() {
  const pts = [];
  for (let i = 0; i <= 60; i++) {
    const t = (i / 60) * 2 * Math.PI;
    const x = 16 * Math.sin(t) ** 3;
    const y = 13 * Math.cos(t) - 5 * Math.cos(2 * t) - 2 * Math.cos(3 * t) - Math.cos(4 * t);
    pts.push([0.5 + x / 50, 0.47 - y / 50]);
  }
  return [pts];
}

function star() {
  const pts = [];
  for (let i = 0; i <= 10; i++) {
    const r = i % 2 === 0 ? 0.34 : 0.14;
    const a = -Math.PI / 2 + (i * Math.PI) / 5;
    pts.push([0.5 + r * Math.cos(a), 0.53 + r * Math.sin(a)]);
  }
  return [pts];
}

